module tb_mux4x1_function;

reg I0;
reg I1;
reg I2;
reg I3;

reg [1:0] S;

wire Y;

//---------------------------------------------

mux4x1_function DUT(

.I0(I0),
.I1(I1),
.I2(I2),
.I3(I3),

.S(S),

.Y(Y)

);

//---------------------------------------------

initial begin

    $fsdbDumpfile("dump.fsdb");
    $fsdbDumpvars(0,tb_mux4x1_function);

    $display("-------------------------------------------------------------");
    $display("Time\tS\tI0 I1 I2 I3\tY");
    $display("-------------------------------------------------------------");

    $monitor("%0t\t%b\t%b  %b  %b  %b\t%b",
             $time,S,I0,I1,I2,I3,Y);

    //-----------------------------------------

    // Fixed Inputs
    I0 = 0;
    I1 = 1;
    I2 = 0;
    I3 = 1;

    //-----------------------------------------

    S = 2'b00; #10;

    S = 2'b01; #10;

    S = 2'b10; #10;

    S = 2'b11; #10;

    //-----------------------------------------

    // Change Inputs

    I0 = 1;
    I1 = 0;
    I2 = 1;
    I3 = 0;

    S = 2'b00; #10;

    S = 2'b01; #10;

    S = 2'b10; #10;

    S = 2'b11; #10;

    //-----------------------------------------

    #10;
    $finish;

end

endmodule